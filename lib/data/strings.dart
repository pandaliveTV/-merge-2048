  static String get(String lang, String key, [Map<String, Object>? args]) {
    var s = _values[lang]?[key] ?? _values['en']![key] ?? key;
    args?.forEach((k, v) => s = s.replaceAll('{$k}', '$v'));
    return s;
  }

  /// Every key present in English must exist in Arabic (checked in tests).
  static Set<String> missingKeys(String lang) =>
      _values['en']!.keys.toSet().difference(_values[lang]!.keys.toSet());
}

extension Tr on BuildContext {
  String tr(String key, [Map<String, Object>? args]) {
    final lang = Localizations.localeOf(this).languageCode;
    return AppStrings.get(lang, key, args);
  }
